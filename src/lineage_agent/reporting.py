"""Render BlastRadius results as portable Markdown review artifacts."""

import os
import tempfile
from pathlib import Path
from typing import Any


def _inline_code(value: str) -> str:
    """Keep user-provided metadata on one safe Markdown line."""
    return value.replace("`", "&#96;").replace("\r", " ").replace("\n", " ")


def render_markdown_report(
    result: Any,
    *,
    source_urn: str,
    instruction: str,
    artifact_summary: str | None = None,
) -> str:
    """Render a generated change as a PR-ready Markdown report."""
    artifacts = (
        "## Generated downstream artifacts\n\n"
        f"{artifact_summary}\n\n"
        if artifact_summary
        else ""
    )
    return (
        "# BlastRadius Change Impact Report\n\n"
        "> Proposed change only. BlastRadius does not execute this SQL. "
        "A human must review the migration and every tracked consumer.\n\n"
        f"- Source asset: `{_inline_code(source_urn)}`\n"
        f"- Request: `{_inline_code(instruction)}`\n"
        f"- Generator: `{_inline_code(result.generator)}`\n\n"
        "## Proposed SQL\n\n"
        "```sql\n"
        f"{result.change_sql}\n"
        "```\n\n"
        "## DataHub impact analysis\n\n"
        f"{result.impact.summary}\n\n"
        f"{artifacts}"
        "---\n\n"
        "Generated by BlastRadius from DataHub metadata. Missing lineage may mean "
        "untracked dependencies, not a safe change.\n"
    )


def write_markdown_report(content: str, destination: str | Path) -> Path:
    """Atomically write a report and return its resolved destination."""
    output_path = Path(destination).expanduser().resolve()
    output_path.parent.mkdir(parents=True, exist_ok=True)
    temp_path: Path | None = None
    try:
        with tempfile.NamedTemporaryFile(
            mode="w",
            encoding="utf-8",
            newline="\n",
            dir=output_path.parent,
            prefix=f".{output_path.name}.",
            suffix=".tmp",
            delete=False,
        ) as handle:
            handle.write(content)
            temp_path = Path(handle.name)
        os.replace(temp_path, output_path)
    finally:
        if temp_path is not None and temp_path.exists():
            temp_path.unlink()
    return output_path
